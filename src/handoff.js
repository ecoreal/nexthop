// HANDOFF.md generation — the community-convention artifact (goal / where it
// stands / files touched / next steps), filled from a parsed session. The
// extraction is heuristic and labelled as such, right in the file.

import { resumeHints } from "./hints.js";

export { resumeHints };

export function buildHandoffMd(session, { cwd } = {}) {
  const started = session.startedAt ? session.startedAt.slice(0, 16).replace("T", " ") : "?";
  const last = session.lastAt ? session.lastAt.slice(0, 16).replace("T", " ") : "?";

  const files = session.filesTouched.length
    ? session.filesTouched.map((f) => `- \`${f}\``).join("\n")
    : "_none detected in this session_";
  const cmdCounts = new Map();
  for (const c of session.commands) {
    const key = c.split("\n")[0].slice(0, 90);
    cmdCounts.set(key, (cmdCounts.get(key) || 0) + 1);
  }
  const commands = cmdCounts.size
    ? [...cmdCounts.entries()]
        .sort((a, b) => b[1] - a[1])
        .slice(0, 8)
        .map(([c, n]) => `- \`${c}${n > 1 ? `\` (×${n})` : "`"}`)
        .join("\n")
    : "_none detected_";

  return `# Handoff

> Generated by **nexthop** from a ${session.label} session.
> Heuristic summary from the session log — verify before acting.

| | |
| --- | --- |
| Session | \`${session.sessionId}\` |
| Working dir | \`${cwd || session.cwd || "?"}\` |
| Window | ${started} → ${last} |
| Size | ${session.turns} user turns · ${session.filesTouched.length} files touched |

## Goal

${session.firstUser || "_(not captured)_"}

## Where it stands

${truncate(session.lastAssistant || session.lastUser, 1200) || "_(not captured)_"}

## Last user instruction

${truncate(session.lastUser, 600) || "_(not captured)_"}

## Files touched

${files}

## Commands worth knowing

${commands}

## Suggested next steps

1. Read the files above and run the project's tests to confirm the current state.
2. Pick up from the last user instruction.
3. Ask the previous agent's transcript for detail if something looks off:
   \`${session.file}\`

## Resume

${resumeHints(session).map((h) => `- \`${h}\``).join("\n")}

## Source session

- CLI: ${session.label} (\`${session.cli}\`)
- Log: \`${session.file}\`
`;
}

function truncate(s, n) {
  s = String(s || "").trim();
  return s.length <= n ? s : s.slice(0, n) + "\n… (truncated — read the source session for the full context)";
}

